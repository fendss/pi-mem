import type { PiMemSelection } from "../../../model/evidence.js";
import type { CreatePiMemToolsOptions, FinishToolDetails, PiMemTools } from "./contracts.js";
import { FinishParameters } from "./schemas.js";
import { compactPreview } from "../../../../util.js";

export function createFinishTool(
  options: CreatePiMemToolsOptions,
): PiMemTools["finish"] {
  return {
    name: "finish",
    label: "Finish",
    description:
      "Stop retrieval and commit every exact source returned by read. The " +
      "harness generates citations, hashes, provenance, deduplication, and formatting. " +
      "Call this alone, only after observing the latest search or read result in " +
      "an earlier assistant turn.",
    parameters: FinishParameters,
    executionMode: "sequential",
    async execute(_toolCallId, params) {
      const evidence = options.ledger.inspectedEvidence;
      if (params.status === "sufficient" && evidence.length === 0) {
        throw new Error(
          "Finish rejected: sufficient retrieval requires at least one exact " +
            "source returned by read.",
        );
      }
      const submitted: PiMemSelection = {
        status: params.status,
        citations: evidence.map((source) => ({
          memoryId: source.memoryId,
          supports: compactPreview(source.content, 360),
        })),
        ...(params.evidenceSummary === undefined ? {} : { evidenceSummary: params.evidenceSummary }),
      };
      await options.beforeFinish?.(submitted);
      const selection = options.ledger.finish(submitted);
      const details: FinishToolDetails = {
        kind: "finish",
        committedEvidenceRefs: evidence.map((source) =>
          options.ledger.evidenceRef(source.memoryId)!
        ),
        committedEvidence: evidence.map((source) => ({
          memoryId: source.memoryId,
          scopeId: source.scopeId,
          sessionId: source.sessionId,
          turnIndex: source.turnIndex,
          role: source.role,
          ...(source.timestamp === undefined
            ? {}
            : { timestamp: source.timestamp }),
          contentHash: source.contentHash,
          sourceContentHash: source.sourceContentHash,
          sourceContentLength: source.sourceContentLength,
          truncated: source.truncated,
        })),
        selection,
      };
      return {
        content: [{
          type: "text",
          text: `Committed all ${String(evidence.length)} read exact source(s); ` +
            "citations, hashes, and provenance were generated by the harness.",
        }],
        details,
        terminate: true,
      };
    },
  };
}
